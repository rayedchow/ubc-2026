export const categoryById = (id: string | null | undefined) => CATEGORIES.find((c) => c.id === id);

type Seed = Omit<Gym, "checks" | "graderVersion" | "codeHash"> & { grader: [version: string, hash: string] };

function checks(gym: Seed): QualityCheck[] {
  if (gym.status === "soon") return [];
  return [
    { label: "No-op fails, gold passes", proves: "The grader can tell right from wrong", passed: true },
    { label: "Shortcut suite", proves: "Known hacks earn no reward", passed: true },
    { label: "Second-grader agreement", proves: "Scores are not one grader's quirk", passed: true },
    {
      label: "Judge validation",
      proves: gym.grading.usesJudge
        ? "The judge matches expert labels: error rates measured, graded 5 times, judge swapped"
        : "No LLM judge is used; grading is code only",
      passed: true,
    },
    { label: "Difficulty band", proves: "Tasks are hard but learnable", passed: true },
    { label: "Why frontier models fail", proves: "The tasks measure a real gap", passed: true },
    { label: "Measured improvement", proves: "Training here has worked for others", passed: gym.report !== null },
  ];
}

