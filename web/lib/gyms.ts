export const GYMS: Gym[] = SEEDS.map(({ grader, ...gym }) => ({
  ...gym,
  // How a Gym grades is something buyers filter on, so it is always a tag.
  tags: [...gym.tags, gym.grading.usesJudge ? "LLM judge" : "Code-graded"],
  graderVersion: grader[0],
  codeHash: grader[1],
  checks: checks({ grader, ...gym }),
}));

export const gymById = (id: string) => GYMS.find((g) => g.id === id);

/** Every tag in use, most common first, for the tag filter. */
export const ALL_TAGS: string[] = (() => {
  const count = new Map<string, number>();
  for (const gym of GYMS) for (const tag of gym.tags) count.set(tag, (count.get(tag) ?? 0) + 1);
  return [...count.keys()].sort((a, b) => count.get(b)! - count.get(a)! || a.localeCompare(b));
})();
